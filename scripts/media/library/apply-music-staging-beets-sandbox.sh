#!/usr/bin/env bash
set -u

APP_DIR="/srv/toolbox/app"
LIB_DIR="$APP_DIR/scripts/lib"

source "$LIB_DIR/logging.sh"
source "$LIB_DIR/timestamps.sh"
source "$LIB_DIR/tsv.sh"
source "$LIB_DIR/paths.sh"

STAMP="$(toolbox_timestamp)"
SHARED_DIR="$(toolbox_shared_dir)"

BEETS_SANDBOX_ROOT="$SHARED_DIR/beets/media-staging"
BEETS_CONFIG="$BEETS_SANDBOX_ROOT/config.yaml"
BEETS_LIBRARY="$BEETS_SANDBOX_ROOT/library.blb"
BEETS_STAGING_LIBRARY="$BEETS_SANDBOX_ROOT/library"

REPORT_DIR="$SHARED_DIR/reports/media/staging"
RAW_DIR="$SHARED_DIR/library-db/raw/media/staging"
SNAPSHOT_DIR="$SHARED_DIR/library-db/snapshots/media/staging"

REPORT="$REPORT_DIR/music_staging_beets_sandbox_apply_report_$STAMP.txt"
TSV="$RAW_DIR/music_staging_beets_sandbox_apply_$STAMP.tsv"

APPLY_MODE="${1:-}"

require_function() {
  local fn="$1"

  if ! declare -F "$fn" >/dev/null 2>&1; then
    printf '%s\n' "[ERRO] Required function not found: $fn" >&2
    exit 1
  fi
}

require_lib_contract() {
  require_function log
  require_function fail
  require_function toolbox_timestamp
  require_function toolbox_now
  require_function toolbox_shared_dir
  require_function tsv_row
}

write_step() {
  local step_id="$1"
  local phase="$2"
  local target="$3"
  local status="$4"
  local action="$5"
  local notes="$6"

  tsv_row "$step_id" "$phase" "$target" "$status" "$action" "$notes" >> "$TSV"
}

append_section() {
  local title="$1"

  {
    printf '\n'
    printf '## %s\n' "$title"
    printf '\n'
  } >> "$REPORT"
}

confirm_apply() {
  local confirmation

  if [ "$APPLY_MODE" != "--apply" ]; then
    fail "This script modifies the Beets sandbox. Re-run with: apply-music-staging-beets-sandbox.sh --apply"
  fi

  printf '%s\n' "This script will create/update the Beets sandbox:"
  printf '%s\n' "- $BEETS_SANDBOX_ROOT"
  printf '%s\n' "- $BEETS_CONFIG"
  printf '%s\n' "- $BEETS_STAGING_LIBRARY"
  printf '%s\n' "It will not run beet import, write tags, move files, or modify /srv/media/music."
  printf '%s' "Type APPLY to continue: "
  read -r confirmation

  if [ "$confirmation" != "APPLY" ]; then
    fail "Apply aborted by user."
  fi
}

safe_name_for_path() {
  local path="$1"

  printf '%s' "$path" | sed 's#^/##; s#[/ ]#_#g'
}

backup_file() {
  local file="$1"
  local safe_name
  local backup_path

  mkdir -p "$SNAPSHOT_DIR"

  if [ ! -f "$file" ]; then
    write_step "BACKUP" "backup" "$file" "SKIP" "file does not exist yet" ""
    return 0
  fi

  safe_name="$(safe_name_for_path "$file")"
  backup_path="$SNAPSHOT_DIR/${safe_name}_backup_$STAMP"

  cp -a "$file" "$backup_path"
  write_step "BACKUP" "backup" "$file" "OK" "created backup" "$backup_path"
}

run_report_command() {
  local step_id="$1"
  local phase="$2"
  local command_label="$3"
  shift 3

  append_section "$step_id - $phase"

  {
    printf '%s\n' '```text'
    printf '$'
    printf ' %q' "$@"
    printf '\n\n'
  } >> "$REPORT"

  if "$@" >> "$REPORT" 2>&1; then
    printf '\n%s\n' '[OK]' >> "$REPORT"
    printf '%s\n' '```' >> "$REPORT"
    write_step "$step_id" "$phase" "$command_label" "OK" "command succeeded" ""
    return 0
  fi

  printf '\n%s\n' '[FAIL]' >> "$REPORT"
  printf '%s\n' '```' >> "$REPORT"
  write_step "$step_id" "$phase" "$command_label" "FAIL" "command failed" ""
  return 1
}

validate_no_plugin_errors_in_report() {
  local step_id="$1"
  local label="$2"
  local found

  found="$(
    grep -Ei 'error loading plugin|PluginImportError|ModuleNotFoundError|Could not import plugin|No module named' "$REPORT" || true
  )"

  if [ -z "$found" ]; then
    write_step "$step_id" "validate" "$label" "OK" "no plugin import/load errors detected" ""
    return 0
  fi

  write_step "$step_id" "validate" "$label" "FAIL" "plugin import/load errors detected" "$found"
  return 1
}

write_beets_config() {
  cat > "$BEETS_CONFIG" <<EOF
# Beets sandbox config for Toolbox music staging review/import workflow.
# Generated by apply-music-staging-beets-sandbox.sh at $(toolbox_now).
#
# Safety policy:
# - no copy
# - no move
# - no write
# - use this sandbox only for MusicBrainz/chroma candidate matching

directory: $BEETS_STAGING_LIBRARY
library: $BEETS_LIBRARY

import:
  copy: no
  write: no
  move: no
  resume: ask
  incremental: no
  timid: yes

plugins: chroma musicbrainz

chroma:
  auto: yes

ui:
  color: yes
EOF
}

validate_file_contains() {
  local step_id="$1"
  local file="$2"
  local pattern="$3"
  local label="$4"

  if grep -q "$pattern" "$file"; then
    write_step "$step_id" "validate" "$file" "OK" "$label found" "$pattern"
    return 0
  fi

  write_step "$step_id" "validate" "$file" "FAIL" "$label missing" "$pattern"
  return 1
}

main() {
  local fail_count
  local warn_count

  require_lib_contract
  confirm_apply

  mkdir -p "$REPORT_DIR" "$RAW_DIR" "$SNAPSHOT_DIR"

  log "Starting music staging Beets sandbox apply."

  tsv_row \
    "step_id" \
    "phase" \
    "target" \
    "status" \
    "action" \
    "notes" > "$TSV"

  {
    printf '%s\n' '# Music Staging Beets Sandbox Apply'
    printf '\n'
    printf 'Generated at: %s\n' "$(toolbox_now)"
    printf 'Host: %s\n' "$(hostname)"
    printf 'User: %s\n' "$(id -un)"
    printf 'Beets sandbox root: %s\n' "$BEETS_SANDBOX_ROOT"
    printf 'Beets config: %s\n' "$BEETS_CONFIG"
    printf 'Beets library DB: %s\n' "$BEETS_LIBRARY"
    printf 'Beets sandbox library dir: %s\n' "$BEETS_STAGING_LIBRARY"
    printf 'Report: %s\n' "$REPORT"
    printf 'TSV: %s\n' "$TSV"
    printf 'Snapshot dir: %s\n' "$SNAPSHOT_DIR"
    printf '\n'
    printf '%s\n' 'Safety: APPLY script. Creates/updates Beets sandbox only. Does not run import, write tags or move files.'
    printf '\n'
  } > "$REPORT"

  if command -v beet >/dev/null 2>&1; then
    write_step "PRE-001" "preflight" "beet" "OK" "beet command found" "$(command -v beet)"
  else
    write_step "PRE-001" "preflight" "beet" "FAIL" "beet command missing" ""
  fi

  if command -v fpcalc >/dev/null 2>&1; then
    write_step "PRE-002" "preflight" "fpcalc" "OK" "fpcalc command found" "$(command -v fpcalc)"
  else
    write_step "PRE-002" "preflight" "fpcalc" "FAIL" "fpcalc command missing" ""
  fi

  mkdir -p "$BEETS_SANDBOX_ROOT"
  mkdir -p "$BEETS_STAGING_LIBRARY"

  write_step "APPLY-001" "apply" "$BEETS_SANDBOX_ROOT" "OK" "ensured sandbox root directory" ""
  write_step "APPLY-002" "apply" "$BEETS_STAGING_LIBRARY" "OK" "ensured sandbox library directory" ""

  backup_file "$BEETS_CONFIG"
  write_beets_config

  write_step "APPLY-003" "apply" "$BEETS_CONFIG" "OK" "wrote Beets sandbox config" ""

  append_section "Generated config"

  {
    printf '%s\n' '```yaml'
    cat "$BEETS_CONFIG"
    printf '%s\n' '```'
  } >> "$REPORT"

  validate_file_contains "VAL-001" "$BEETS_CONFIG" "^directory: $BEETS_STAGING_LIBRARY$" "directory setting"
  validate_file_contains "VAL-002" "$BEETS_CONFIG" "^library: $BEETS_LIBRARY$" "library setting"
  validate_file_contains "VAL-003" "$BEETS_CONFIG" "^  copy: no$" "copy disabled"
  validate_file_contains "VAL-004" "$BEETS_CONFIG" "^  write: no$" "write disabled"
  validate_file_contains "VAL-005" "$BEETS_CONFIG" "^  move: no$" "move disabled"
  validate_file_contains "VAL-006" "$BEETS_CONFIG" "^plugins: chroma musicbrainz$" "chroma plugin"

  run_report_command "VAL-007" "validate" "beet version" beet version
  run_report_command "VAL-008" "validate" "fpcalc -version" fpcalc -version
  validate_no_plugin_errors_in_report "VAL-010" "BEETSDIR beet config"

  fail_count="$(awk -F '\t' 'NR > 1 && $4 == "FAIL" { c++ } END { print c+0 }' "$TSV")"
  warn_count="$(awk -F '\t' 'NR > 1 && $4 == "WARN" { c++ } END { print c+0 }' "$TSV")"

  {
    printf '\n'
    printf '%s\n' '## Summary'
    printf '\n'
    printf 'Failures: %s\n' "$fail_count"
    printf 'Warnings: %s\n' "$warn_count"
    printf '\n'
    printf '%s\n' 'Next phase: run validate-music-staging-beets-sandbox.sh.'
    printf '\n'
    printf '%s\n' 'Generated artifacts:'
    printf '%s\n' "- Report: $REPORT"
    printf '%s\n' "- TSV: $TSV"
  } >> "$REPORT"

  if [ "$fail_count" -gt 0 ]; then
    log "Music staging Beets sandbox apply completed with failures."
    log "Report: $REPORT"
    log "TSV: $TSV"
    exit 1
  fi

  log "Music staging Beets sandbox apply completed."
  log "Report: $REPORT"
  log "TSV: $TSV"
}

main "$@"
